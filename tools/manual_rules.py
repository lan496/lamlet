#!/usr/bin/env python3
"""Generate executable manual constraints and an honest, hash-bound coverage ledger.

Only explicit reviewed templates and definitions enable rules. Unrecognized
prose stays pending; the completeness gate fails until it has a disposition.
"""

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re

from corpus import write_json
from lammps_docs import ROOT, REVISION, VERSION, SIGNAL


def selectors(page):
    result = []
    for alias in page["commands"]:
        words = alias.split()
        if len(words) == 1:
            result.append({"command": words[0]})
        elif len(words) == 2:
            position = 3 if words[0] in ("fix", "compute", "dump") else 1
            result.append({"command": words[0], "position": position, "value": words[1]})
    return result


def locate(text, anchor):
    """Match reviewed text across RST line wrapping, retaining source offsets."""
    match = re.search(r"\s+".join(re.escape(w) for w in anchor.split()), text)
    if match is None:
        raise ValueError(f"Source anchor missing: {anchor!r}")
    return match.start(), match.end()


def review_ledger(texts, rules, reviews):
    """Keep explicit review decisions separate from automatic rule links."""
    if reviews["revision"] != REVISION:
        raise ValueError("Review decisions refer to a different manual revision")
    decisions = {}
    known_rules = {r["id"] for r in rules}
    for review in reviews["paragraphs"]:
        key = review["page"], review["sha256"]
        if key in decisions:
            raise ValueError(f"Duplicate review: {key}")
        if review["status"] not in ("implemented", "partial", "deferred", "runtime_only", "not_lint"):
            raise ValueError(f"Invalid review status: {review['status']}")
        if not review["reason"].strip():
            raise ValueError(f"Review has no rationale: {key}")
        if not set(review["rules"]) <= known_rules:
            raise ValueError(f"Review refers to an unknown rule: {key}")
        if review["status"] == "implemented" and not review["rules"]:
            raise ValueError(f"Implemented paragraph has no rules: {key}")
        decisions[key] = review
    ledger, found = [], set()
    for name, text in texts.items():
        for match in re.finditer(r"(?:[^\n]+\n?)+", text):
            paragraph = match.group().strip()
            if not SIGNAL.search(paragraph):
                continue
            line = text.count("\n", 0, match.start()) + 1
            digest = hashlib.sha256(paragraph.encode()).hexdigest()
            related = [r["id"] for r in rules if r["source"]["page"] == name
                       and r["source"]["start_line"] <= line <= r["source"]["end_line"]]
            key = name, digest
            review = decisions.get(key)
            if review:
                found.add(key)
                if not set(review["rules"]) <= set(related):
                    raise ValueError(f"Review rule does not cite this paragraph: {key}")
            ledger.append({"page": name, "line": line, "sha256": digest,
                           "related_rules": related, "status": review["status"] if review else "pending",
                           "reason": review["reason"] if review else "Not semantically reviewed"})
    if found != set(decisions):
        raise ValueError(f"Stale review decisions: {sorted(set(decisions) - found)}")
    counts = Counter(item["status"] for item in ledger)
    summary = {"candidate_paragraphs": len(ledger),
               "reviewed_paragraphs": len(ledger) - counts["pending"],
               "pending_paragraphs": counts["pending"], "partial_paragraphs": counts["partial"],
               "deferred_paragraphs": counts["deferred"],
               "complete": not any(counts[s] for s in ("pending", "partial", "deferred"))}
    return ledger, summary


def reference(manifest):
    lines = ["# Manual rule catalog", "", "<!-- Generated by tools/manual_rules.py. Do not edit. -->", "",
             f'The catalog contains **{len(manifest["rules"])} executable warning rules** pinned to LAMMPS {VERSION}.',
             "The [lint reference](lint-rules.md) defines state boundaries, Unknown outcomes, and review coverage.",
             "The catalog does not cover every constraint in the manual.", "",
             "`lamlet schema RULE-ID --format json` returns the predicate, exact selectors, source hash, and executable examples.",
             "Argument positions are zero-based, including the command name at position 0.", "",
             '<div class="lamlet-rule-catalog" markdown>', "",
             "| Rule and source | Condition and applicability |", "| --- | --- |"]
    for rule in manifest["rules"]:
        labels = []
        for selected in rule["selectors"]:
            label = selected["command"]
            if "value" in selected:
                label += "/" + selected["value"]
            if "active_pair_style" in selected:
                label += " with " + selected["active_pair_style"]
            if selected.get("exact_arguments"):
                label += f' ({selected["exact_arguments"] - 1} operands)'
            labels.append(label)
        source = rule["source"]
        lines.append(f'| `{rule["id"]}`<br>[{source["page"].removesuffix(".rst")}:{source["start_line"]}]({source["url"]})'
                     + f' | {rule["message"]}.<br>' + ", ".join(f"`{s}`" for s in labels) + " |")
    lines.extend(["", "</div>", ""])
    return "\n".join(lines)


def generate(args):
    catalog = json.loads((ROOT / "crates/lamlet/data/lammps_docs.json").read_text())
    if catalog["revision"] != REVISION:
        raise ValueError("Manual catalog revision mismatch")
    pages = {p["path"]: p for p in catalog["pages"]}
    texts = {}
    for name, page in pages.items():
        data = (args.text / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != page["sha256"]:
            raise ValueError(f"Manual source changed: {name}")
        texts[name] = data.decode("utf-8")
    rules = []

    def add(key, page, anchor, predicate, message, examples, selected=None):
        text = texts[page]
        at, _ = locate(text, anchor)
        previous = text.rfind("\n\n", 0, at)
        start = previous + 2 if previous >= 0 else 0
        end = text.find("\n\n", at)
        end = len(text) if end < 0 else end
        rules.append({"id": "LML-MAN-" + key, "message": message,
                      "selectors": selected if selected is not None else selectors(pages[page]),
                      "predicate": predicate, "severity": "warning", "autofix": False,
                      "source": {"page": page, "sha256": pages[page]["sha256"],
                                 "start_line": text.count("\n", 0, start) + 1,
                                 "end_line": text.count("\n", 0, end) + 1,
                                 "url": pages[page]["source_url"] + "#L" + str(text.count("\n", 0, start) + 1)},
                      "examples": examples})

    # These whole-command restrictions have an explicit subject and box boundary.
    before = re.compile(r"This command (?:cannot be used \*?after\*?|must (?:be used|come) before) the simulation box is defined")
    after = re.compile(r"This command must (?:be used|come) after the simulation box is defined")
    for name, text in texts.items():
        for pattern, kind in ((before, "before_box"), (after, "after_box")):
            match = pattern.search(re.sub(r"\s+", " ", text))
            if match and len(selectors(pages[name])) == 1 and "position" not in selectors(pages[name])[0]:
                command = selectors(pages[name])[0]["command"]
                arguments = {"units": "metal", "boundary": "p p p", "dimension": "3", "atom_style": "atomic", "processors": "* * *", "package": "omp 1", "mass": "1 1.0", "thermo_style": "one", "labelmap": "atom 1 H"}.get(command, "* 1.0")
                line = f"{command} {arguments}\n"
                add(command.upper() + "-" + kind.upper().replace("_", "-"), name,
                    match.group(), {"kind": kind},
                    f"{command} requires the simulation box to be {'undefined' if kind == 'before_box' else 'defined'}",
                    [{"input": ("create_box 1 box\n" if kind == "before_box" else "") + line, "outcome": "violated"},
                     {"input": ("create_box 1 box\n" if kind == "after_box" else "") + line, "outcome": "satisfied"},
                     {"input": "include opaque.in\n" + line, "outcome": "unknown"}])

    def numeric(key, page, anchor, command, position, minimum, examples, integer=False, maximum=None, exclusive=False, selected=None):
        add(key, page + ".rst", anchor,
            {"kind": "number", "position": position, "minimum": minimum,
             "maximum": maximum, "integer": integer, "exclusive": exclusive},
            f"{command} argument {position} must be {'an integer' if integer else 'finite'} and {'greater than' if exclusive else 'at least'} {minimum}" + (f" and at most {maximum}" if maximum is not None else ""),
            examples, selected if selected is not None else [{"command": command}])

    add("DIMENSION", "dimension.rst", "* N = 2 or 3",
        {"kind": "one_of", "position": 1, "values": ["2", "3"]},
        "dimension must be 2 or 3", [{"input": "dimension 4\n", "outcome": "violated"}, {"input": "dimension 2\n", "outcome": "satisfied"}])
    add("BOUNDARY-FACES", "boundary.rst", "The *p* style must be applied to both faces",
        {"kind": "boundary_faces"}, "Periodic boundaries must apply to both faces of each dimension",
        [{"input": "boundary pf p p\n", "outcome": "violated"}, {"input": "boundary fs pp m\n", "outcome": "satisfied"}])
    numeric("MASS", "mass", "The mass assigned to any type or atom must be > 0.0.", "mass", 2, 0,
            [{"input": "mass 1 0\n", "outcome": "violated"}, {"input": "mass 1 1.0\n", "outcome": "satisfied"}], exclusive=True)
    numeric("RUN-LIMIT", "run", "must fit in a signed 32-bit integer", "run", 1, 0,
            [{"input": "run 2147483648\n", "outcome": "violated"}, {"input": "run 0\n", "outcome": "satisfied"}], integer=True, maximum=2147483647,
            selected=[{"command": "run", "exact_arguments": 2}])
    for style, page in [("ave/time", "fix_ave_time"), ("ave/atom", "fix_ave_atom"), ("ave/chunk", "fix_ave_chunk"), ("ave/grid", "fix_ave_grid"), ("ave/histo", "fix_ave_histo")]:
        add(style.upper().replace("/", "-"), page + ".rst", r"must be a multiple of :math:`N_\text{every}`",
            {"kind": "sampling", "positions": [4, 5, 6]},
            "Averaging requires positive integer Nevery, Nrepeat and Nfreq, Nfreq divisible by Nevery, and Nevery*Nrepeat <= Nfreq",
            [{"input": f"fix sample all {style} 3 2 10 c_value\n", "outcome": "violated"},
             {"input": f"fix sample all {style} 2 5 10 c_value\n", "outcome": "satisfied"}],
            [{"command": "fix", "position": 3, "value": style}])

    # Bind an explicit positive-integer annotation to a fixed positional syntax
    # parameter. Optional keywords and alternative style grammars are excluded.
    annotation = re.compile(r"^\* (?P<parameter>\w+) = [^\n]*\((?P<kind>positive integer|non-negative integer)\)", re.M)
    for name, text in texts.items():
        syntax = next((s for s in pages[name]["sections"] if s["title"] == "Syntax"), None)
        if syntax is None or name == "fix_langevin.rst":  # Existing LML-LINT-002.
            continue
        lines = text.splitlines()
        section = "\n".join(lines[syntax["start_line"] - 1:syntax["end_line"]])
        prototype = re.search(r"\.\. code-block:: LAMMPS\n\n +([^\n]+)", section)
        if not prototype:
            continue
        words = prototype.group(1).split()
        possible = selectors(pages[name])
        chosen = [s for s in possible if words and s["command"] == words[0]
                  and ("position" not in s or (len(words) > s["position"] and
                       (s["value"] == words[s["position"]] or
                        any(s["value"] == words[s["position"]] + suffix for suffix in ("/omp", "/kk", "/gpu", "/intel", "/opt")))))]
        if not chosen:
            continue
        for match in annotation.finditer(section):
            parameter = match["parameter"]
            if words.count(parameter) != 1:
                continue
            position = words.index(parameter)
            if any(w in ("...", "args", "keyword", "values") for w in words[:position]):
                continue
            key = name.removesuffix(".rst").upper().replace("_", "-") + "-" + parameter.upper()
            sample = ["sample" if w == "ID" else "all" if w == "group-ID" else "1" if i > (3 if words[0] in ("fix", "compute", "dump") else 1) else w for i, w in enumerate(words[:position + 1])]
            examples = []
            for value, expected in [("-1" if match["kind"] == "non-negative integer" else "0", "violated"), ("1", "satisfied"), ('"${value}"', "unknown")]:
                sample[position] = value
                examples.append({"input": " ".join(sample) + "\n", "outcome": expected})
            numeric(key, name.removesuffix(".rst"), match.group(), words[0], position,
                    0 if match["kind"] == "non-negative integer" else 1, examples, integer=True, selected=chosen)
    for style, anchor in [("cfg", 'file, a wildcard "\\*" must be included in the filename'),
                          ("grid/vtk", 'The filename for this style must include a "\\*" wildcard')]:
        add("DUMP-PATTERN-" + style.upper().replace("/", "-"), "dump.rst", anchor,
            {"kind": "contains", "position": 5, "value": "*"},
            f"dump {style} requires a '*' filename wildcard for separate snapshots",
            [{"input": f"dump d all {style} 10 single.out\n", "outcome": "violated"},
             {"input": f"dump d all {style} 10 snapshot.*\n", "outcome": "satisfied"}],
            [{"command": "dump", "position": 3, "value": style}])

    # Styles with an unconditional, whole-style three-dimensional restriction.
    dimension_pattern = re.compile(r"(?:This (?:fix(?: style)?|compute|pair style)|These (?:fixes|computes)) (?:can only be used (?:in|with)|is only (?:available|usable) (?:in|for)|cannot be used in) (?:3d|3D|three-dimensional|2D) (?:simulations|systems)")
    for name, text in texts.items():
        match = dimension_pattern.search(re.sub(r"\s+", " ", text))
        if match:
            if "cannot" not in match.group() or "2D" in match.group():
                add(name.removesuffix(".rst").upper().replace("_", "-") + "-3D", name, match.group(),
                    {"kind": "dimension", "expected": 3}, "This style requires a three-dimensional simulation", [])

    for page, anchor in [
        ("compute_viscosity_cos", "it cannot be used for 2d systems."),
        ("fix_accelerate_cos", "it cannot be used in 2d simulations."),
        ("fix_charge_regulation", "Only usable for 3D simulations with orthogonal simulation boxes"),
        ("fix_widom", "Only usable for 3D simulations."),
    ]:
        add(page.upper().replace("_", "-") + "-3D", page + ".rst", anchor,
            {"kind": "dimension", "expected": 3}, "This style requires a three-dimensional simulation", [])
    for family, anchor in [
        (("msm",), "For MSM, a simulation must be 3d"),
        (("ewald", "esp", "pppm"), "For Ewald, ESP and PPPM, a simulation must be 3d"),
    ]:
        selected = [s for s in selectors(pages["kspace_style.rst"]) if s.get("value", "").split("/")[0] in family]
        add("KSPACE-" + family[0].upper() + "-3D", "kspace_style.rst", anchor,
            {"kind": "dimension", "expected": 3}, "This kspace style requires a three-dimensional simulation", [], selected)
    add("AVE-GRID-2D", "fix_ave_grid.rst", "For 2d simulations, *Nz* must be 1.",
        {"kind": "dimensional_argument", "position": 9, "dimension": 2, "expected": 1},
        "fix ave/grid requires Nz = 1 in two dimensions",
        [{"input": "dimension 2\nfix sample all ave/grid 1 1 10 2 2 2 temp\n", "outcome": "violated"},
         {"input": "dimension 2\nfix sample all ave/grid 1 1 10 2 2 1 temp\n", "outcome": "satisfied"},
         {"input": "include state.in\nfix sample all ave/grid 1 1 10 2 2 2 temp\n", "outcome": "unknown"}])

    def state_rule(key, page, anchor, kind, message, command, cases, selected=None):
        add(key, page + ".rst", anchor, {"kind": kind}, message,
            [{"input": text, "outcome": expected} for text, expected in cases],
            selected if selected is not None else [{"command": command}])

    state_rule("NEIGHBOR-DELAY", "neigh_modify", "If the *delay* setting is non-zero, then it must be a multiple of the *every* setting.",
               "neighbor_delay", "Neighbor delay must be zero or a nonnegative multiple of a positive every setting", "neigh_modify",
               [("neigh_modify delay 3 every 2\n", "violated"), ("neigh_modify delay 4 every 2\n", "satisfied"),
                ('neigh_modify delay "${delay}" every 2\n', "unknown")])
    state_rule("NEIGHBOR-PAGE", "neigh_modify", "The value of the *page* setting must be at least 10x larger than the *one* setting.",
               "neighbor_page", "Neighbor page must be at least ten times one", "neigh_modify",
               [("neigh_modify page 100 one 11\n", "violated"), ("neigh_modify page 100 one 10\n", "satisfied"),
                ('neigh_modify page "${page}" one 10\n', "unknown")])
    state_rule("PAIR-SHIFT-TAIL", "pair_modify", "You cannot use *shift* yes with *tail* yes", "pair_shift_tail",
               "Pair energy shifting and tail corrections cannot both be enabled", "pair_modify",
               [("pair_modify shift yes tail yes\n", "violated"), ("pair_modify shift yes tail no\n", "satisfied"),
                ("pair_modify pair lj/cut shift yes tail yes\n", "unknown")])
    state_rule("PAIR-TAIL-2D", "pair_modify", "You cannot use *tail* yes with 2d simulations.", "pair_tail_dimension",
               "Pair tail corrections require three dimensions", "pair_modify",
               [("dimension 2\npair_modify tail yes\n", "violated"), ("dimension 3\npair_modify tail yes\n", "satisfied"),
                ("include state.in\npair_modify tail yes\n", "unknown")])
    state_rule("RESET-DUMP", "dump", "While a dump command is active", "reset_dump",
               "Stop active dumps with undump before resetting the timestep", "reset_timestep",
               [("dump d all atom 100 atoms.dump\nreset_timestep 0\n", "violated"),
                ("dump d all atom 100 atoms.dump\nundump d\nreset_timestep 0\n", "satisfied"),
                ("dump d all atom 100 atoms.dump\ninclude state.in\nreset_timestep 0\n", "unknown")])
    state_rule("RESET-TIME-FIX", "reset_timestep", "This command cannot be used when any fixes are defined that keep track of elapsed time", "reset_time_fix",
               "Time-tracking fixes must be removed before resetting the timestep", "reset_timestep",
               [("fix step all dt/reset 1 0.0001 0.01 0.1\nreset_timestep 0\n", "violated"),
                ("fix step all dt/reset 1 0.0001 0.01 0.1\nunfix step\nreset_timestep 0\n", "satisfied"),
                ("include state.in\nreset_timestep 0\n", "unknown")])
    state_rule("READ-DATA-ADD", "read_data", "If a simulation box does not yet exist, the *add* keyword cannot be used", "read_data_add",
               "read_data requires add exactly when a simulation box already exists", "read_data",
               [("read_data atoms.data add append\n", "violated"), ("read_data atoms.data\n", "satisfied"),
                ("include state.in\nread_data atoms.data\n", "unknown")])
    state_rule("READ-DATA-OPTIONS", "read_data", "The *offset* and *shift* keywords can only be used if the *add* keyword is also specified.", "read_data_options",
               "read_data offset and shift require add", "read_data",
               [("read_data atoms.data shift 0 0 1\n", "violated"), ("read_data atoms.data add append shift 0 0 1\n", "satisfied"),
                ("read_data atoms.data unknown_option add\n", "unknown")])
    for command, page, anchor in [("processors", "processors", "*Pz* must equal 1."),
                                   ("replicate", "replicate", "A 2d simulation cannot be replicated in the z dimension.")]:
        add(command.upper() + "-2D", page + ".rst", anchor,
            {"kind": "dimensional_argument", "position": 3, "dimension": 2, "expected": 1},
            f"{command} requires z count 1 in two dimensions",
            [{"input": f"dimension 2\n{command} 1 1 2\n", "outcome": "violated"},
             {"input": f"dimension 2\n{command} 1 1 1\n", "outcome": "satisfied"},
             {"input": f'include state.in\n{command} 1 1 2\n', "outcome": "unknown"}])
    for style, page, anchor in [("msd", "compute_msd", "Compute *msd* cannot be used with a dynamic group"),
                                ("msd/nongauss", "compute_msd_nongauss", "Compute *msd/nongauss* cannot be used with a dynamic group"),
                                ("tgnvt/drude", "fix_tgnh_drude", "These fixes cannot be used with dynamic groups")]:
        command = "fix" if page.startswith("fix_") else "compute"
        chosen = selectors(pages[page + ".rst"]) if command == "fix" else [{"command": command, "position": 3, "value": style}]
        state_rule(page.upper().replace("_", "-") + "-GROUP", page, anchor, "static_group",
                   "This style requires a static group", command,
                   [(f"group mobile dynamic all every 10\n{command} value mobile {style}\n", "violated"),
                    (f"{command} value all {style}\n", "satisfied"),
                    (f"include state.in\n{command} value mobile {style}\n", "unknown")], chosen)
    state_rule("COMM-MULTI", "comm_modify", "Communication mode *multi* is currently only available for :doc:`comm_style <comm_style>` *brick*", "comm_multi",
               "Multi communication requires comm_style brick", "comm_modify",
               [("comm_style tiled\ncomm_modify mode multi\n", "violated"), ("comm_style brick\ncomm_modify mode multi\n", "satisfied"),
                ("include state.in\ncomm_modify mode multi\n", "unknown")])
    state_rule("NVE-SPHERE-DISC", "fix_nve_sphere", "Use of the *disc* keyword is only allowed for 2d simulations", "disc_dimension",
               "nve/sphere disc requires two dimensions", "fix",
               [("fix integrate all nve/sphere disc\n", "violated"), ("dimension 2\nfix integrate all nve/sphere disc\n", "satisfied"),
                ("include state.in\nfix integrate all nve/sphere disc\n", "unknown")],
               [{"command": "fix", "position": 3, "value": "nve/sphere"}])

    # Every template instance carries executable three-way examples. These are
    # applicability tests, not claims that an isolated command runs a simulation.
    for rule in rules:
        if rule["predicate"]["kind"] == "dimension" and not rule["examples"]:
            selected = rule["selectors"][0]
            command = selected["command"]
            line = f'{command} sample all {selected["value"]}\n' if command in ("fix", "compute", "dump") else f'{command} {selected["value"]}\n'
            rule["examples"] = [{"input": "dimension 2\n" + line, "outcome": "violated"},
                                {"input": "dimension 3\n" + line, "outcome": "satisfied"},
                                {"input": "include state.in\n" + line, "outcome": "unknown"}]

    for key, page, anchor, allowed, chosen in [
        ("AMOEBA-UNITS", "pair_amoeba", "Thus you can only use these pair styles with real units.", ["real"], None),
        ("D3-UNITS", "pair_dispersion_d3", "The compiled in parameters require the use of :doc:`metal units <units>`.", ["metal"], None),
        ("POLARIZE-UNITS", "fix_polarize", "Note that the *polarize/bem/gmres* and *polarize/bem/icc* fixes only support", ["lj", "real", "metal", "si", "nano"],
         [{"command": "fix", "position": 3, "value": style} for style in ("polarize/bem/gmres", "polarize/bem/icc")]),
        ("QMMM-XTB-UNITS", "fix_qmmm_xtb", "only ``real`` and ``metal`` units are supported", ["real", "metal"], None),
    ]:
        chosen = chosen if chosen is not None else selectors(pages[page + ".rst"])
        selected = next(s for s in chosen if s.get("value") and not s["value"].endswith("/gpu"))
        line = f'fix sample all {selected["value"]}\n' if selected["command"] == "fix" else f'pair_style {selected["value"]}\n'
        invalid = next(u for u in ("cgs", "lj", "real", "metal") if u not in allowed)
        add(key, page + ".rst", anchor, {"kind": "units", "allowed": allowed},
            "This style requires units " + ", ".join(allowed),
            [{"input": f"units {invalid}\n" + line, "outcome": "violated"},
             {"input": f"units {allowed[0]}\n" + line, "outcome": "satisfied"},
             {"input": "include state.in\n" + line, "outcome": "unknown"}], chosen)

    unsupported = re.compile(r"^(?:This pair style|These pair styles) (?:does|do) not support the :doc:`pair_modify(?: <pair_modify>)?` ([^.]+)\.")
    for name, text in texts.items():
        if not name.startswith("pair_"):
            continue
        for paragraph in re.split(r"\n\s*\n", text):
            match = unsupported.match(re.sub(r"\s+", " ", paragraph).strip())
            if not match:
                continue
            # Interpret only the named, reviewed options, never arbitrary prose.
            options = [option for option in ("shift", "table", "tail") if re.search(r"\b" + option + r"\b", match[1].split("option")[0])]
            chosen = [s for s in selectors(pages[name]) if s["command"] == "pair_style" and "value" in s]
            for option in options:
                key = name.removesuffix(".rst").upper().replace("_", "-") + "-MODIFY-" + option.upper()
                style = chosen[0]["value"]
                add(key, name, match.group(), {"kind": "pair_unsupported", "option": option},
                    f"The selected pair style does not support pair_modify {option}",
                    [{"input": f"pair_style {style}\npair_modify {option} " + ("12" if option == "table" else "yes") + "\n", "outcome": "violated"},
                     {"input": f"pair_style {style}\npair_modify {option} " + ("0" if option == "table" else "no") + "\n", "outcome": "satisfied"},
                     {"input": f'pair_style {style}\npair_modify {option} "${{value}}"\n', "outcome": "unknown"}],
                    [{"command": "pair_modify", "active_pair_style": s["value"]} for s in chosen])

    if len({r["id"] for r in rules}) != len(rules):
        raise ValueError("Duplicate rule IDs")
    if any(not rule["selectors"] for rule in rules):
        raise ValueError("Rule has no unambiguous selector")
    rules.sort(key=lambda r: r["id"])
    ledger, summary = review_ledger(texts, rules, json.loads(args.reviews.read_text()))
    manifest = {"schema_version": 1, "revision": REVISION, "version": VERSION, "rules": rules, "review": summary,
                "commands": sorted({alias.split()[0] for page in pages.values() for alias in page["commands"]})}
    if args.check:
        if json.loads(args.output.read_text()) != manifest:
            raise SystemExit("Manual rule catalog is out of date; regenerate it")
        if args.docs.read_text() != reference(manifest):
            raise SystemExit("Manual rule reference is out of date; regenerate it")
    else:
        write_json(args.output, manifest)
        args.docs.write_text(reference(manifest))
        write_json(args.ledger, {"revision": REVISION, "candidates": ledger, **summary})
    print(json.dumps({"rules": len(rules), **summary}))
    if args.require_complete and not summary["complete"]:
        raise SystemExit("Manual conversion is incomplete: pending, partial or deferred paragraphs remain")


